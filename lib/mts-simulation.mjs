const SIM_DEFAULT = {product:'Мобильная сеть МТС',service:'Доступность сервиса',title:'Нарушение доступности учебного сервиса',summary:'В учебном сценарии сервис не отвечает на запросы.'};
export function mtsSimulationFields(item){
  const known=SIM_CASES[item.id];
  if(known)return {...known};
  const product=SIM_PRODUCTS[item.product||item.productName]||item.product||item.productName||SIM_DEFAULT.product;
  if(/МТС|Биллинг/.test(product))return {product,service:item.service||SIM_DEFAULT.service,title:item.title||item.header||SIM_DEFAULT.title,summary:item.summary||item.shortDescription||SIM_DEFAULT.summary};
  return {...SIM_DEFAULT,product:SIM_PRODUCTS[product]||(/МТС|Биллинг/.test(product)?product:SIM_DEFAULT.product)};
}
export function mtsSimulationText(value){
  let text=String(value??'');
  for(const [original,product] of Object.entries(SIM_PRODUCTS))text=text.replaceAll(original,product);
  return text;
}
export function mtsSimulationEvent(event){
  const scenario=SIM_CASES[event.incidentId];
  return {...event,detail:scenario?scenario.product+' · '+scenario.service:mtsSimulationText(event.detail),changes:(event.changes||[]).map(c=>({...c,before:mtsSimulationText(c.before),after:mtsSimulationText(c.after)}))};
}
export function projectMtsSimulation(snapshot){
  const incidents=snapshot.incidents.map(item=>{
    const fields=mtsSimulationFields(item),recovered=['resolved','closed','investigating'].includes(item.status);
    return {...item,...fields,description:'Симуляция: '+fields.summary,scenario:'Учебный сценарий · '+fields.service,solution:recovered?'В учебном сценарии работоспособность сервиса восстановлена. Точная причина в данных не подтверждена.':'',isSimulated:true,itsmUrl:null,demoItsmUrl:'/itsm-demo?incident='+encodeURIComponent(item.id)};
  });
  return {...snapshot,incidents,events:snapshot.events?.map(mtsSimulationEvent),simulation:{enabled:true,label:'Симуляция МТС',message:'Вымышленные сбои телеком-сервисов. Исполнители, статусы, приоритеты и сроки сохранены из учебной выгрузки.'},meta:{...snapshot.meta,products:new Set(incidents.map(i=>i.product)).size}};
}
export function makeMtsSimulationRaw(rows){
  return rows.map(row=>{
    const fields=mtsSimulationFields(row),recovered=['Resolved','Closed','Research'].includes(row.stateEnum);
    return {...row,productName:fields.product,header:fields.title,service:fields.service,scenarioName:'Учебный сценарий · '+fields.service,shortDescription:fields.summary,description:'Симуляция: '+fields.summary,solution:recovered?'В учебном сценарии сервис восстановлен. Причина уточняется.':'',productUrl:''};
  });
}
